-- =================================================================
-- SCRIPT DE CRIAÇÃO DA TABELA: rpa_execucoes
-- Repositório: ds-rpa-control-center
-- =================================================================

CREATE TABLE rpa_execucoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_robot TEXT NOT NULL,                         -- Exemplo: '001', '002'
    robot_name TEXT NOT NULL,                       -- Exemplo: 'Faturação', 'Extratos'
    start_time_date DATE NOT NULL,                  -- Data de início (YYYY-MM-DD)
    start_time_hour TIME NOT NULL,                  -- Hora de início (HH:MM:SS)
    end_time_date DATE,                             -- Data de fim (YYYY-MM-DD)
    end_time_hour TIME,                             -- Hora de fim (HH:MM:SS)
    duration_seconds INT,                           -- Duração total em segundos
    status TEXT NOT NULL,                           -- 'OK' ou 'KO'
    error_category TEXT,                            -- Categoria do erro se status = 'KO'
    
    -- Ambiente: Padrão 'PRD'. Só permite 'PRD' ou 'DEV'
    environment TEXT DEFAULT 'PRD' 
        CONSTRAINT chk_environment CHECK (environment IN ('PRD', 'DEV')),
        
    -- Modo de Execução: Padrão 'Manual'. Só permite 'Manual' ou 'Agendado'
    mode TEXT DEFAULT 'Manual' 
        CONSTRAINT chk_mode CHECK (mode IN ('Manual', 'Agendado')),
        
    logs TEXT,                                      -- Registos detalhados em texto
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Comentários para documentação do esquema
COMMENT ON COLUMN rpa_execucoes.environment IS 'Ambiente de execução: PRD (Produção) ou DEV (Desenvolvimento)';
COMMENT ON COLUMN rpa_execucoes.mode IS 'Modo de disparo: Manual (Default) ou Agendado';
